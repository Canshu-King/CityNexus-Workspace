# ---- zip, manifest from the archive, verify -------------------------------
if os.path.exists(ZIP):
    os.remove(ZIP)
with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as archive:
    for base, _dirs, files in os.walk(STAGE):
        for fn in sorted(files):
            full = os.path.join(base, fn)
            arc = os.path.relpath(full, STAGE).replace(os.sep, "/")
            if arc == "MANIFEST.txt":
                continue
            archive.write(full, arc)

lines = []
with zipfile.ZipFile(ZIP) as archive:
    for info in sorted(archive.infolist(), key=lambda i: i.filename):
        blob = archive.read(info.filename)
        lines.append("%s  %8d  %s" % (hashlib.sha256(blob).hexdigest(), len(blob), info.filename))
manifest = ("# pass-15 archive manifest — generated by reading %s back after writing it\n"
            "# columns: sha256  bytes  path\n\n" % NAME) + "\n".join(lines) + "\n"
with zipfile.ZipFile(ZIP, "a", zipfile.ZIP_DEFLATED) as archive:
    archive.writestr("MANIFEST.txt", manifest)

with zipfile.ZipFile(ZIP) as archive:
    listed = {}
    for row in archive.read("MANIFEST.txt").decode("utf-8").splitlines():
        if row and not row.startswith("#"):
            digest_hex, size, name = row.split(None, 2)
            listed[name] = (digest_hex, int(size))
    in_archive = {i.filename for i in archive.infolist()}
    problems = []
    for name, (digest_hex, size) in listed.items():
        blob = archive.read(name)
        if hashlib.sha256(blob).hexdigest() != digest_hex or len(blob) != size:
            problems.append("hash/size mismatch: " + name)
    for name in in_archive - set(listed) - {"MANIFEST.txt"}:
        problems.append("in archive but not listed: " + name)
    for name in set(listed) - in_archive:
        problems.append("listed but missing: " + name)

print("gates tree:", gates[:7], "HEAD:", head[:7])
print("entries listed:", len(listed))
print("verification:", "OK" if not problems else problems)
print("zip sha256:", sha256(ZIP))
print("zip bytes:", os.path.getsize(ZIP))
