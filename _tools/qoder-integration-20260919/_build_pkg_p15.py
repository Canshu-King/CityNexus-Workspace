def git(*args):
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True,
                          text=True, encoding="utf-8", errors="replace", check=True).stdout


def git_b(*args):
    """Raw bytes: this tree's diffs are not valid UTF-8 and a patch must stay byte-exact."""
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, check=True).stdout


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


for sub in ("", "patches", "runs", "screens", "provenance"):
    os.makedirs(os.path.join(STAGE, sub), exist_ok=True)

log_lines = git("log", "--pretty=format:%H %s").splitlines()
subjects = dict(ln.split(" ", 1) for ln in log_lines)
head = git("rev-parse", "HEAD").strip()
gates = next((sha for sha, subject in subjects.items() if subject.startswith(GATES_SUBJECT)), None)
if not gates:
    raise SystemExit("could not find the %r commit in HEAD's history" % GATES_SUBJECT)
if subprocess.run(["git", "merge-base", "--is-ancestor", gates, head], cwd=ROOT).returncode != 0:
    raise SystemExit("%s is not an ancestor of HEAD" % gates[:7])
between = git("diff", "--name-only", gates, head).splitlines()
outside = [p for p in between if p != "INTEGRATION_REPORT.md" and not p.startswith("reports/")]
if outside:
    raise SystemExit("HEAD is no longer report-and-evidence only over the gates tree: %s" % outside)

