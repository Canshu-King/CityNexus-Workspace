"""Build the pass-13 evidence package for external review.

Same discipline as pass-12: the manifest is generated by reading the finished
archive back, then re-verified entry by entry, so the package cannot claim a
file it does not carry or omit one it does.
"""

import hashlib
import io
import json
import os
import subprocess
import zipfile

ROOT = os.path.abspath(os.path.dirname(__file__))
STAGE = os.path.join(ROOT, "_pkg_p14")
NAME = "CityNexus-Qoder-pass14-Canonical-E2E-Policy-Legacy-Archive-20260919.zip"
ZIP = os.path.join(ROOT, NAME)
TMP = os.path.join(os.environ["USERPROFILE"], ".qoder", "tmp")
GATES_SUBJECT = "test(e2e): pass-14"


def git(*args):
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True,
                          text=True, encoding="utf-8", errors="replace", check=True).stdout


def git_b(*args):
    """Raw bytes: this tree's diffs are not valid UTF-8 and a patch must stay byte-exact."""
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, check=True).stdout


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


for sub in ("", "patches", "runs", "screens", "provenance"):
    os.makedirs(os.path.join(STAGE, sub), exist_ok=True)

log_lines = git("log", "--pretty=format:%H %s").splitlines()
subjects = dict(ln.split(" ", 1) for ln in log_lines)
head = git("rev-parse", "HEAD").strip()
gates = next((sha for sha, subject in subjects.items() if subject.startswith(GATES_SUBJECT)), None)
if not gates:
    raise SystemExit("could not find the %r commit in HEAD's history" % GATES_SUBJECT)
if subprocess.run(["git", "merge-base", "--is-ancestor", gates, head], cwd=ROOT).returncode != 0:
    raise SystemExit("%s is not an ancestor of HEAD" % gates[:7])
between = git("diff", "--name-only", gates, head).splitlines()
outside = [p for p in between if p != "INTEGRATION_REPORT.md" and not p.startswith("reports/")]
if outside:
    raise SystemExit("HEAD is no longer report-and-evidence only over the gates tree: %s" % outside)

# ---- documents -------------------------------------------------------------
for src, dst in (
    ("INTEGRATION_REPORT.md", "INTEGRATION_REPORT.md"),
    ("docs/LEGACY_E2E_MIGRATION.md", "LEGACY_E2E_MIGRATION.md"),
    ("docs/E2E_ACCEPTANCE_POLICY.md", "E2E_ACCEPTANCE_POLICY.md"),
):
    with io.open(os.path.join(ROOT, src), encoding="utf-8") as handle:
        body = handle.read()
    with io.open(os.path.join(STAGE, dst), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(body)

# ---- commit chain ----------------------------------------------------------
parent = git("rev-parse", "%s~1" % head).strip()
if gates == head:
    relation = (
        "The gates ran on this very commit: its tree holds the code, the report and the\n"
        "evidence images of this pass together, so there is no gap between what was\n"
        "executed and what is committed.  Verify that the code is really in it:\n"
        "  git show --stat %s   ->  backend/app/db/session.py, app/main.py, the provenance\n"
        "     tests, playwright.config.ts, CopilotDock.tsx, design-tokens.css, the two\n"
        "     e2e files, INTEGRATION_REPORT.md and reports/**\n"
        "Its parent %s carries the same report text without the code; a run does not read\n"
        "the report, which is why the numbers are attributed to this commit.\n" % (head[:7], parent[:7])
    )
else:
    relation = (
        "%s adds the report and the evidence images that very run produced; nothing\n" % head[:7]
        + "else changed.  Verify -- the real list, not a description:\n"
        + "".join("  %s\n" % p for p in between)
    )

with io.open(os.path.join(STAGE, "COMMITS.txt"), "w", encoding="utf-8", newline="\n") as handle:
    handle.write(
        "HEAD (this package)   %s  %s\n" % (head[:7], subjects[head])
        + "gates ran on          %s  %s\n" % (gates[:7], subjects[gates])
        + "\n"
        + "Every number in INTEGRATION_REPORT.md sections 40-44 was produced on tree %s.\n" % gates[:7]
        + relation
        + "\nThe authoritative command, verbatim (stdout kept clean for --reporter=json):\n"
        + "  CITYNEXUS_E2E_AUTHORITATIVE=1 CITYNEXUS_E2E_RUN_ID=p14full1 \\\n"
        + "  DEEPSEEK_API_KEY= CITYNEXUS_AI_API_KEY= CITYNEXUS_AI_ENABLED=false \\\n"
        + "  CITYNEXUS_PYTHON='D:\\moodle\\CityNexus\\.venv\\Scripts\\python.exe' \\\n"
        + "  CITYNEXUS_BACKEND_PORT=8036 CITYNEXUS_E2E_PORT=4208 \\\n"
        + "  CITYNEXUS_DATABASE_URL='sqlite:///./_p14full1.db' \\\n"
        + "    npx playwright test --reporter=json\n"
        + "\nNote on patches/: text-mode diffs, so PNG blobs appear as 'Binary files differ'.\n"
        + "The images themselves ship under screens/.\n"
        + "\n--- full chain (newest first) ---\n"
        + git("log", "--pretty=format:%h %ad %s", "--date=format:%m-%d %H:%M", "-34")
    )

# ---- patches ---------------------------------------------------------------
with io.open(os.path.join(STAGE, "patches", "00_cumulative_baseline_to_HEAD.patch"), "wb") as handle:
    handle.write(git_b("diff", "integration/baseline", head))
with io.open(os.path.join(STAGE, "patches", "01_pass14_policy_and_legacy_archive.patch"), "wb") as handle:
    handle.write(git_b("show", "--format=%n%n%s%n%n%b", gates))

# ---- raw run evidence ------------------------------------------------------
for src, dst in (
    ("p14_full.json", "runs/fe_full_pass14_authoritative.json"),
    ("p131_full.json", "runs/fe_full_pass131_authoritative.json"),
    ("p14_backend.log", "runs/backend_p14.log"),
    ("p14_legacy.log", "runs/legacy_suite_p14.log"),
):
    source = os.path.join(TMP, src)
    if not os.path.exists(source):
        raise SystemExit("missing run evidence: %s" % source)
    with open(source, "rb") as handle:
        blob = handle.read()
    with open(os.path.join(STAGE, *dst.split("/")), "wb") as handle:
        handle.write(blob)

# stats digest, quoted from the files rather than retyped
with io.open(os.path.join(STAGE, "runs", "STATS.md"), "w", encoding="utf-8", newline="\n") as handle:
    handle.write(
        "# Playwright stats blocks, read back from the JSON in this archive\n\n"
        "So the numbers quoted in INTEGRATION_REPORT.md section 33 can be traced to one run.\n\n"
    )
    for label, fname in (
        ("pass-14 authoritative current-product suite, tree %s" % gates[:7], "fe_full_pass14_authoritative.json"),
        ("pass-13.1 authoritative suite (before the four archives)", "fe_full_pass131_authoritative.json"),
    ):
        data = json.load(io.open(os.path.join(STAGE, "runs", fname), encoding="utf-8"))["stats"]
        handle.write("`%s` -> `%s`\n\n```\n%s\n```\n\n" % (
            label, fname,
            json.dumps({"expected": data["expected"], "unexpected": data["unexpected"],
                        "flaky": data["flaky"], "skipped": data["skipped"],
                        "duration_ms": round(data["duration"])})))

# ---- provenance record (what the gate asserts about its own run) -----------
with open(os.path.join(ROOT, "reports", "e2e-provenance", "authoritative.json"), "rb") as handle:
    blob = handle.read()
with open(os.path.join(STAGE, "provenance", "authoritative.json"), "wb") as handle:
    handle.write(blob)

# ---- screenshots / geometry evidence ---------------------------------------
changed = [p for p in git("diff", "--name-only", "HEAD~3", head).splitlines()
           if p.endswith(".png") or p.endswith(".json")]
for rel in changed:
    full = os.path.join(ROOT, rel)
    if not os.path.exists(full):
        continue
    with open(full, "rb") as handle:
        blob = handle.read()
    with open(os.path.join(STAGE, "screens", rel.replace("/", "__")), "wb") as handle:
        handle.write(blob)

